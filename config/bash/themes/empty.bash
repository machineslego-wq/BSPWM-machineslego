# ==========================================================
# empty.bash — пустой пресет: шаблон для своей темы
# ==========================================================
# Репозиторий: config/bash/themes → ~/.config/bash/themes
# Подключение: BASH_PROMPT=empty в ~/.bashrc
#              или BASH_PROMPT=empty bash (на один запуск).
#
# Контракт пресета: файл только выставляет PS1 (и при необходимости
# PROMPT_COMMAND). Больше ничего не нужно — ~/.bashrc подключает
# его через `.` и сам PS1 не трогает.
#
# Как сделать свою тему:
#   1. cp ~/.config/bash/themes/empty.bash ~/.config/bash/themes/my-theme.bash
#   2. Раскомментируй нужный вариант ниже и поправь цвета/сегменты.
#   3. BASH_PROMPT=my-theme bash — посмотреть; затем вписать имя в ~/.bashrc.
# ==========================================================

# Сброс прошлой темы: если пресет перезагружают в текущем шелле
# (`source ~/.bashrc`), старая функция не должна остаться в PROMPT_COMMAND.
