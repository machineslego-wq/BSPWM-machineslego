# ----------------------------------------------------------
# Вариант 1 (сейчас активен): пустой промпт, как у стокового bash
# ----------------------------------------------------------
# \u — пользователь, \h — хост, \w — путь от ~ (\W — только последний
# каталог), \$ — # для root и $ для обычного пользователя.
