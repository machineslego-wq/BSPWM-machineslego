#!/bin/bash
# =========================================================
# brightness.sh — Модуль яркости для Polybar
# =========================================================
# Скрипт работает в режиме `tail = true` и выводит данные
# только при изменении яркости (снижает нагрузку на CPU).
# =========================================================

# ---------------------------------------------------------
# --- Настройки отображения ---
# ---------------------------------------------------------
# STYLE — стиль отображения:
#   "icon"     — только иконка и процент (пример: 󰃞 45%)
#   "bar"      — только полоса и процент   (пример: ••◦◦◦ 45%)
#   "both"     — иконка + полоса + процент (пример: 󰃞 ••◦◦◦ 45%)
#   "icon-bar" — иконка + полоса, без процента
#   "bar-icon" — полоса + иконка + процент
STYLE="both"

# Ширина полосы (в сегментах)
BAR_WIDTH=5

# ---------------------------------------------------------
# --- Цвета (Tokyo Night) ---
# ---------------------------------------------------------
COLOR_BAR="%{F#7aa2f7}"     # заполненная часть — синий primary
COLOR_BG="%{F#565f89}"      # пустая часть — приглушённый
COLOR_RESET="%{F-}"         # сброс цвета

# ---------------------------------------------------------
# --- Символы для полосы ---
# ---------------------------------------------------------
# Маленькие (рекомендуется для FHD, выглядит аккуратно)
CHAR_FILL="•"
CHAR_EMPTY="◦"

# Большие (если захочется поэкспериментировать)
# CHAR_FILL="●"
# CHAR_EMPTY="○"

# =========================================================
# --- Основная логика ---
# =========================================================

# Переменная для отслеживания изменений (оптимизация вывода)
last=""

while true; do
    # Получаем текущую и максимальную яркость
    current=$(brightnessctl g 2>/dev/null)
    max=$(brightnessctl m 2>/dev/null)

    # Проверка на ошибки чтения (например, если нет подсветки)
    if [ -z "$current" ] || [ -z "$max" ] || [ "$max" -eq 0 ]; then
        out="N/A"
    else
        # Вычисляем процент яркости
        percent=$(( current * 100 / max ))

        # --- Выбор иконки по уровню яркости ---
        if   [ "$percent" -le 49 ]; then icon="󰃞"
        elif [ "$percent" -le 90 ]; then icon="󰃟"
        else                             icon="󰃠"
        fi

        # --- Генерация полосы прогресса ---
        filled=$(( percent * BAR_WIDTH / 100 ))
        empty=$(( BAR_WIDTH - filled ))

        # Включаем шрифт font-2 (в нем символы точек выглядят лучше)
        bar="%{T2}${COLOR_BAR}"
        
        # Заполненные сегменты
        for ((i=0; i<filled; i++)); do 
            bar="${bar}${CHAR_FILL}" 
        done
        
        # Пустые сегменты
        bar="${bar}${COLOR_BG}"
        for ((i=0; i<empty; i++)); do 
            bar="${bar}${CHAR_EMPTY}" 
        done
        
        # Сброс цвета и возврат шрифта font-0 для текста
        bar="${bar}${COLOR_RESET}%{T-}"

        # --- Сборка итоговой строки в зависимости от STYLE ---
        case "$STYLE" in
            "icon")     out="${icon} ${percent}%" ;;
            "bar")      out="${bar} ${percent}%" ;;
            "both")     out="${icon} ${bar} ${percent}%" ;;
            "icon-bar") out="${icon} ${bar}" ;;
            "bar-icon") out="${bar} ${icon} ${percent}%" ;;
            *)          out="${icon} ${percent}%" ;;  # запасной вариант
        esac
    fi

    # Выводим результат только если он изменился
    if [ "$out" != "$last" ]; then
        echo "$out"
        last="$out"
    fi

    # Пауза перед следующей проверкой
    # 0.1 сек — это очень быстро, яркость будет реагировать мгновенно.
    sleep 0.1
done