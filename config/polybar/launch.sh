#!/bin/bash
# ==========================================================
# launch.sh — Запуск Polybar с автоопределением железа
# ==========================================================
# Скрипт определяет имя батареи и адаптера питания,
# экспортирует их в переменные окружения и перезапускает
# панель (убивая старые экземпляры).
# ==========================================================

# ---------------------------------------------------------
# --- 1. Автоопределение батареи ---
# ---------------------------------------------------------
for bat in /sys/class/power_supply/BAT*; do
    if [ -d "$bat" ]; then
        # Экспортируем имя (например, BAT0 или BAT1) для Polybar
        export POLYBAR_BAT=$(basename "$bat")
        break
    fi
done

# ---------------------------------------------------------
# --- 2. Автоопределение адаптера питания (AC) ---
# ---------------------------------------------------------
for ac in /sys/class/power_supply/*; do
    # Адаптер определяется по наличию файла "online"
    if [ -f "$ac/online" ]; then
        # Экспортируем имя (например, AC или ADP1) для Polybar
        export POLYBAR_AC=$(basename "$ac")
        break
    fi
done

# ---------------------------------------------------------
# --- 3. Автоопределение карты подсветки (Backlight) ---
# ---------------------------------------------------------
for bl in /sys/class/backlight/*; do
    if [ -d "$bl" ]; then
        export POLYBAR_BACKLIGHT=$(basename "$bl")
        break
    fi
done

# ---------------------------------------------------------
# --- 4. Перезапуск Polybar ---
# ---------------------------------------------------------

# Убиваем все существующие процессы Polybar
pkill -x polybar

# Убить старые экземпляры модулей-скриптов (они не убиваются при pkill -x polybar)
pkill -f "polybar/scripts/power-profile.sh" 2>/dev/null

# Ждём, пока они полностью завершатся (чтобы избежать конфликтов)
while pgrep -u "$(id -u)" -x polybar > /dev/null; do 
    sleep 1
done

# Запускаем главную панель в фоне
polybar main &