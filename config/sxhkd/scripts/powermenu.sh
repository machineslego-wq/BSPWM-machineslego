#!/bin/bash
# ==========================================================
# powermenu.sh — Меню питания (Rofi)
# ==========================================================
# При вызове сразу открывает меню выбора действия.
# ==========================================================

# --- НАСТРОЙКА ---
# Ширина окна Rofi в процентах от ширины экрана.
WIDTH=20

# --- МЕНЮ ВЫБОРА ---
# Блокировка, Выключить и Выйти сверху, Перезагрузить внизу
CHOICE=$(printf "Заблокировать\nВыключить\nВыйти\nПерезагрузить" | \
    rofi -dmenu -p "Питание" -theme-str "window {width: ${WIDTH}%;}")

# Если нажали Esc (меню закрылось пустым) — выходим
[ -z "$CHOICE" ] && exit 0

# --- ЛОГИКА (БЕЗ ПОДТВЕРЖДЕНИЯ) ---
case "$CHOICE" in
    *"Заблокировать"*)
        sleep 0.5 && i3lock-fancy -p
        ;;
    *"Выключить"*)
        systemctl poweroff
        ;;
    *"Выйти"*)
        bspc quit
        ;;
    *"Перезагрузить"*)
        systemctl reboot
        ;;
esac