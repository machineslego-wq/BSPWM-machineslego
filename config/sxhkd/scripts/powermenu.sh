#!/bin/bash
# ==========================================================
# powermenu.sh — Меню питания (Rofi)
# ==========================================================
# При вызове сразу открывает меню выбора действия.
# ==========================================================

# --- НАСТРОЙКА ---
# Ширина окна Rofi в процентах от ширины экрана.
WIDTH=20

# --- МЕНЮ ВЫБОРА ---
# Выключить и Выйти сверху, Перезагрузить внизу (как просил)
CHOICE=$(printf "󰐥 Выключить\n󰍃 Выйти\n󰜉 Перезагрузить" | \
    rofi -dmenu -p "󰤆 Питание" -theme-str "window {width: ${WIDTH}%;}")

# Если нажали Esc (меню закрылось пустым) — выходим
[ -z "$CHOICE" ] && exit 0

# --- ЛОГИКА (БЕЗ ПОДТВЕРЖДЕНИЯ) ---
case "$CHOICE" in
    *"Выключить"*)
        systemctl poweroff
        ;;
    *"Выйти"*)
        bspc quit
        ;;
    *"Перезагрузить"*)
        systemctl reboot
        ;;
esac