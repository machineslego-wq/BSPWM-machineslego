#!/bin/bash
# Автоматическая шпаргалка, которая читает sxhkdrc

awk '
# Пропускаем строки-разделители (===)
/^# ===/ { next }

# Если это комментарий, запоминаем его текст (убирая #)
/^# / {
    desc = substr($0, 3)
    next
}

# Если это бинд (начинается с буквы или цифры)
/^[a-zA-Z0-9]/ && !/^#/ {
    if (desc != "") {
        # Выводим бинд и описание (35 символов отводится под бинд)
        printf "%-35s %s\n", $0, desc
        desc = ""
    } else {
        print $0
    }
}

# Сбрасываем описание на пустой строке
/^$/ {
    desc = ""
}
' ~/.config/sxhkd/sxhkdrc | rofi -dmenu -i -p "󰌌 Горячие клавиши" -theme-str 'window {width: 70%; height: 60%;} listview {lines: 15; scrollbar: true;}'